"""Independent graph metrics: extras, wrong merges and abstentions are explicit."""
import itertools
import json
from pathlib import Path
import sys

ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'backend'))


def ratio(n,d):return n/d if d else None


def counts(tp,fp,fn):
    precision=ratio(tp,tp+fp);recall=ratio(tp,tp+fn)
    return {'tp':tp,'fp':fp,'fn':fn,'precision':precision,'recall':recall,
            'f1':ratio(2*tp,2*tp+fp+fn)}


def measure(truth,prediction):
    def facts(graph):
        refs={c['ref']:c['value'] for c in graph['components']}
        pins={(p['ref'],str(p['pin'])):n['name'] for n in graph['nets'] for p in n['nodes']}
        inventory={(p['ref'],str(p['pin'])) for p in graph.get('physical_pins',[])}|pins.keys()
        pairs={tuple(sorted(pair)) for n in graph['nets'] for pair in itertools.combinations(
               sorted({(p['ref'],str(p['pin'])) for p in n['nodes']}),2)}
        return refs,pins,inventory,pairs
    a,ap,ai,at=facts(truth);b,bp,bi,bt=facts(prediction)
    correct={(key,value) for key,value in ap.items()}&{(key,value) for key,value in bp.items()}
    return {'component_detection':counts(len(a.keys()&b.keys()),len(b.keys()-a.keys()),len(a.keys()-b.keys())),
            'component_extras':sorted(b.keys()-a.keys()),'component_omissions':sorted(a.keys()-b.keys()),
            'physical_pin_coverage':counts(len(ai&bi),len(bi-ai),len(ai-bi)),
            'pin_to_net_exact':{'correct':len(correct),'gold_assignments':len(ap),'predicted_assignments':len(bp),
                                'scope':'Literal net labels; autogenerated-name invariant topology is measured separately'},
            'topology_pairwise':{**counts(len(at&bt),len(bt-at),len(at-bt)),
                                 'incorrect_merges':len(bt-at),'wrong_pairs':sorted(bt-at)},
            'abstention':{'observed_unassigned_pins':len(bi-bp.keys()),'gold_pins_without_assignment':len(ai-bp.keys()),
                          'unreviewed_hotspots':sum(not h.get('reviewed') and not h.get('stale') for h in prediction.get('review_hotspots',[]))},
            'whole_graph_exact':a==b and at==bt and ai==bi}


if __name__=='__main__':
    import argparse
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('truth',type=Path);p.add_argument('prediction',type=Path);p.add_argument('--out',type=Path,required=True)
    args=p.parse_args();result=measure(json.loads(args.truth.read_text()),json.loads(args.prediction.read_text()))
    args.out.write_text(json.dumps(result,indent=2));print(json.dumps(result,indent=2))
