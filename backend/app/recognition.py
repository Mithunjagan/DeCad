"""Source-independent recognition checks and conservative document assembly.

These checks identify incomplete proposals; they do not certify source accuracy.
No component family, sample filename or expected circuit is built into them.
"""
from collections import Counter, defaultdict
import hashlib
import re

from .engine import OperationError

UNKNOWN_VALUES = {'UNKNOWN', 'UNREADABLE', '?'}


def pin_map(circuit):
    return {(node.ref, node.pin): net.name for net in circuit.nets for node in net.nodes}


def anonymous_net(name):
    return re.fullmatch(r'(?:N\d+|NET[_$]?\d+|Net-\(.+\))', name, re.I) is not None


def same_value(ref, first, second):
    if first == second:
        return True
    # K/k are the same kilo prefix. Preserve M/m: treating those as equal
    # would conceal a billion-fold component-value disagreement.
    return ref.startswith(('R','C','L')) and first.replace('K','k') == second.replace('K','k')


def review_issues(circuit):
    pins = pin_map(circuit)
    attached = {ref for ref, _ in pins}
    issues = []
    missing = [c.ref for c in circuit.components if c.ref not in attached]
    if missing:
        issues.append('No recovered pin connections for: ' + ', '.join(missing[:30]) + '.')
    unknown = [c.ref for c in circuit.components
               if c.value.strip().upper() in UNKNOWN_VALUES or re.fullmatch(r'U_\d+', c.ref)]
    if unknown:
        issues.append('Unresolved reference or value for: ' + ', '.join(unknown[:30]) + '.')
    if circuit.nets and all(len(net.nodes) == 1 for net in circuit.nets):
        issues.append('Only isolated pin nets were recovered; connected wiring has not been established.')
    return issues


def compare_candidates(local, general):
    """Compare observed physical pins, independent of autogenerated net names.

Return disagreements and whether the general proposal strictly covers the local
observations. Never union graphs: that could join contradictory wire readings.
"""
    a = {c.ref: c.value.strip() for c in local.components}
    b = {c.ref: c.value.strip() for c in general.components}
    conflicts = [f'{ref} value ({a[ref]} / {b[ref]})' for ref in sorted(a.keys() & b.keys())
                 if not same_value(ref,a[ref],b[ref]) and a[ref].upper() not in UNKNOWN_VALUES]
    ap, bp = pin_map(local), pin_map(general)
    shared = ap.keys() & bp.keys()
    labels = sorted({f'{pin[0]}.{pin[1]} net label ({ap[pin]} / {bp[pin]})' for pin in shared
                     if ap[pin] != bp[pin] and not anonymous_net(ap[pin]) and not anonymous_net(bp[pin])})
    conflicts.extend(labels)
    by_a, by_b = defaultdict(set), defaultdict(set)
    for pin in shared:
        by_a[ap[pin]].add(bp[pin])
        by_b[bp[pin]].add(ap[pin])
    if any(len(v) > 1 for v in by_a.values()):
        conflicts.append('a local connection is split in the vision proposal')
    if any(len(v) > 1 for v in by_b.values()):
        conflicts.append('separate local nets are joined in the vision proposal')
    covers = (not conflicts and a.keys() <= b.keys() and ap.keys() <= bp.keys())
    return conflicts, covers


def finish(circuit):
    for issue in review_issues(circuit):
        if issue not in circuit.warnings:
            circuit.warnings.append(issue)
    return circuit


def combine_pages(pages):
    """Flatten page proposals with explicit namespaces rather than guessing hierarchy.

Repeated references can describe separate circuits or sections of the same device.
Keep them separate for review. Likewise, a repeated label is not evidence that
two pages share a global net. Original names remain visible in the scoped names.
"""
    from .ingestion import Circuit, Net

    if len(pages) == 1:
        return finish(pages[0][1])
    if not pages:
        raise OperationError('The document has no nonblank schematic pages.')
    counts = Counter(c.ref for _, circuit in pages for c in circuit.components)
    occupied = set(counts)
    components, nets, warnings = [], [], []
    for page, circuit in pages:
        mapping = {}
        for component in circuit.components:
            ref = component.ref
            if counts[ref] > 1:
                base, number = re.fullmatch(r'(.*?)(\d+)', ref).groups()
                scoped = f'{base}_P{page}_{number}'
                while scoped in occupied:
                    scoped = re.sub(r'(\d+)$', lambda m: m[1] + '0', scoped)
                occupied.add(scoped)
                mapping[ref] = scoped
                warnings.append(f'Page {page}: source reference {ref} is represented as {scoped}; confirm cross-page device identity.')
            else:
                mapping[ref] = ref
            components.append(component.model_copy(update={'ref': mapping[ref], 'x': None, 'y': None}))
        for net in circuit.nets:
            name = f'PAGE{page}_{net.name}'
            if len(name) > 100:
                name = name[:83] + '_' + hashlib.sha256(name.encode()).hexdigest()[:16]
            nets.append(Net(name=name, nodes=[node.model_copy(update={'ref': mapping[node.ref]}) for node in net.nodes]))
        warnings.extend(f'Page {page}: {message}' for message in circuit.warnings)
    warnings.insert(0, f'Recognized {len(pages)} document pages. Page nets remain separate; review off-page/global connections and repeated device sections before combining them.')
    return finish(Circuit(components=components, nets=nets, warnings=warnings))
